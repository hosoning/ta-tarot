function normalizeQuestion(text) {
  if (!text) return "";
  let s = String(text);
  s = s.replace(/[？?！!。，,、．.\s～~…─—\-：:；;「」『』“”"''（）()【】\[\]《》<>]/g, "");
  let out = "";
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    out += ZH_HANT_TO_HANS[ch] || ch;
  }
  return out.toLowerCase();
}


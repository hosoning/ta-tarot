/** 同分时更具体的意图优先（数组靠前） */
const INTENT_TIE_ORDER = INTENT_IDS.reduce(function (acc, id, i) {
  acc[id] = i;
  return acc;
}, {});

function classifyQuestion(text) {
  const q = normalizeQuestion(text);
  if (!q) return "general";

  let best = null;
  // bestScore: [maxLen, lastIndex, totalLen, -tieOrder]
  for (let i = 0; i < INTENTS.length; i++) {
    const intent = INTENTS[i];
    let maxLen = 0;
    let lastIndex = -1;
    let totalLen = 0;
    const kws = intent.keywords;
    for (let k = 0; k < kws.length; k++) {
      const kw = normalizeQuestion(kws[k]);
      if (!kw) continue;
      const idx = q.indexOf(kw);
      if (idx === -1) continue;
      totalLen += kw.length;
      if (kw.length > maxLen || (kw.length === maxLen && idx >= lastIndex)) {
        maxLen = kw.length;
        lastIndex = idx;
      }
    }
    if (maxLen === 0) continue;
    const score = [maxLen, lastIndex, totalLen, -(INTENT_TIE_ORDER[intent.id] || 99)];
    if (
      !best ||
      score[0] > best.score[0] ||
      (score[0] === best.score[0] && score[1] > best.score[1]) ||
      (score[0] === best.score[0] && score[1] === best.score[1] && score[2] > best.score[2]) ||
      (score[0] === best.score[0] && score[1] === best.score[1] && score[2] === best.score[2] && score[3] > best.score[3])
    ) {
      best = { id: intent.id, score: score };
    }
  }
  return best ? best.id : "general";
}

function intentToTheme(intentId) {
  return INTENT_TO_THEME[intentId] || "free";
}


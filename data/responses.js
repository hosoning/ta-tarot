/**
 * 根据牌义倾向判断 positive / neutral / challenging
 */
function getCardPolarity(card, isReversed) {
  const meaning = isReversed ? card.reversed : card.upright;
  const keywords = meaning.keywords.join(" ");
  const challengingWords = ["犹豫", "逃避", "停滞", "失控", "失落", "焦虑", "束缚", "结束", "崩塌", "迷雾", "抗拒", "拖延", "失衡", "冲突", "疲惫", "封闭", "孤独", "失望", "阻碍", "压抑"];
  const positiveWords = ["开始", "创造", "滋养", "前进", "勇气", "转机", "希望", "喜悦", "圆满", "和谐", "连接", "修复", "清晰", "满足", "胜利", "成长"];
  
  let score = 0;
  challengingWords.forEach(w => { if (keywords.includes(w)) score -= 1; });
  positiveWords.forEach(w => { if (keywords.includes(w)) score += 1; });
  
  if (score > 0) return "positive";
  if (score < 0) return "challenging";
  return "neutral";
}

/**
 * 获取传讯文案
 * @param {string} themeId
 * @param {object} card - TAROT_CARDS 中的牌对象
 * @param {boolean} isReversed
 * @param {string} toneId
 * @returns {string} 完整自然段落
 */
function getResponse(themeId, card, isReversed, toneId) {
  const orientation = isReversed ? "reversed" : "upright";
  const themeRes = RESPONSES[themeId];
  
  // 1. 尝试精确匹配
  if (themeRes && themeRes[card.id] && themeRes[card.id][orientation]) {
    const tonePool = themeRes[card.id][orientation][toneId] || themeRes[card.id][orientation]["gentle"];
    if (tonePool && tonePool.length > 0) {
      return tonePool[Math.floor(Math.random() * tonePool.length)];
    }
  }
  
  // 2. 同主题其他语气
  if (themeRes && themeRes[card.id] && themeRes[card.id][orientation]) {
    const allTones = Object.values(themeRes[card.id][orientation]).flat();
    if (allTones.length > 0) {
      return allTones[Math.floor(Math.random() * allTones.length)];
    }
  }
  
  // 3. 使用通用完整文案，按极性对齐
  const polarity = getCardPolarity(card, isReversed);
  const generic = GENERIC_RESPONSES[themeId] || GENERIC_RESPONSES.free;
  const pool = generic[polarity] || generic.neutral;
  return pool[Math.floor(Math.random() * pool.length)];
}

